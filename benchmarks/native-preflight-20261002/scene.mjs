import * as THREE from "/three.webgpu.js";
const renderer = new THREE.WebGPURenderer({ antialias: true, alpha: false, forceWebGL: false });
renderer.setPixelRatio(1);
renderer.setSize(800, 800);
renderer.toneMapping = THREE.ACESFilmicToneMapping;
renderer.toneMappingExposure = 1;
document.body.appendChild(renderer.domElement);
await renderer.init();
if (renderer.backend.isWebGPUBackend !== true) throw new Error("Native WebGPU backend required");
const scene = new THREE.Scene();
scene.background = new THREE.Color(0xd9dfdf);
const camera = new THREE.PerspectiveCamera(42, 1, 0.1, 100);
camera.position.set(5, 4, 6); camera.lookAt(0, 0.4, 0);
scene.add(new THREE.HemisphereLight(0xddefff, 0x8a765d, 2));
const sun = new THREE.DirectionalLight(0xffefd7, 3);
sun.position.set(-3, 7, 5); scene.add(sun);
